"""Write BENCHMARKS.md from the result files (nothing in it is typed by hand).

    python benchmarks/report.py
"""
import json
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from accuracy import JEV_PUBLISHED  # noqa: E402
from suites import SUITES  # noqa: E402

R = os.path.join(HERE, "results")


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def fmt(v, best):
    return ("**%.3f**" % v) if best else "%.3f" % v


def main():
    out = ["# cbjev benchmarks", "",
           "Everything below is generated by `benchmarks/report.py` from the JSON files in `benchmarks/results/`.",
           "cbjev and Laya were run on the same machine, through their public `predict` APIs, on byte-identical "
           "cases (fixed seed 13, 400 cases per suite unless noted). Jev figures are third-party published numbers "
           "and were **never measured here** (no TypeSafe API access): different samples, indicative only.", ""]
    acc = load("accuracy.json")
    if acc:
        res = acc["results"]
        cb = res["cbjev"]
        la, td = res.get("laya", {}), res.get("laya-td", {})
        suites = [s for s in cb if s in la]
        out += ["## Accuracy and calibration, English", "",
                "*train-split*: cbjev trained on that dataset's train split and is scored on its test split (Laya's "
                "docs list the same datasets as in its training mix). *held-out*: never trained on by cbjev.", "",
                "| suite | relation | cbjev | laya | laya-typed-decisions | Jev (published) | cbjev ECE | best Laya ECE |",
                "|---|---|---|---|---|---|---|---|"]
        wins = 0
        for s in suites:
            a, b, c = cb[s]["accuracy"], la[s]["accuracy"], td.get(s, {}).get("accuracy", float("nan"))
            m = max(a, b, c)
            wins += a >= max(b, c)
            j = JEV_PUBLISHED.get(s, {}).get("accuracy")
            out.append("| %s | %s | %s | %s | %s | %s | %.3f | %.3f |" % (
                s, SUITES[s]["relation"], fmt(a, a == m), fmt(b, b == m), fmt(c, c == m),
                "%.3f" % j if j else "", cb[s]["ece"], min(la[s]["ece"], td.get(s, {}).get("ece", 9))))
        mean = lambda e: st.mean(res[e][s]["accuracy"] for s in suites)  # noqa: E731
        mece = lambda e: st.mean(res[e][s]["ece"] for s in suites)  # noqa: E731
        out += ["", "cbjev >= the better Laya checkpoint on **%d / %d** suites. Mean accuracy: cbjev **%.4f**, "
                "laya %.4f, laya-typed-decisions %.4f. Mean ECE: cbjev **%.4f**, laya %.4f, laya-typed-decisions %.4f."
                % (wins, len(suites), mean("cbjev"), mean("laya"), mean("laya-td"), mece("cbjev"), mece("laya"),
                   mece("laya-td")), ""]
        t = cb.get("typed_decisions")
        if t:
            out += ["### typed-decisions (400 cases, 2,000 decisions)", "",
                    "| model | accuracy | soft accuracy | Brier | ECE | score MAE |", "|---|---|---|---|---|---|"]
            for e, name in (("cbjev", "cbjev"), ("laya-td", "laya-typed-decisions"), ("laya", "laya")):
                r = res.get(e, {}).get("typed_decisions")
                if r:
                    out.append("| %s | %.3f | %.3f | %.3f | %.3f | %.3f |" % (
                        name, r["accuracy"], r["soft_accuracy"], r["brier"], r["ece"], r.get("score_mae", float("nan"))))
            j = JEV_PUBLISHED["typed_decisions"]
            out += ["| *Jev 1.13.0 (published)* | *%.3f* | *%.3f* | | *%.3f* | *%.3f* |" % (
                j["accuracy"], j["soft_accuracy"], j["ece"], j["score_mae"]), ""]
            if "by_workflow" in t:
                out += ["cbjev by workflow: " + ", ".join("%s %.3f" % kv for kv in t["by_workflow"].items()) +
                        "; by type: " + ", ".join("%s %.3f" % kv for kv in t["by_type"].items()) + ".", ""]
    ml = load("multilingual.json")
    if ml:
        a, b = ml["results"]["laya-ml"], ml["results"]["cbjev-multilingual"]
        langs = sorted(a)
        wins = sum(b[k]["accuracy"] >= a[k]["accuracy"] for k in langs)
        out += ["## Multilingual: MASSIVE intent, 51 languages (held out), 20 options, 100 cases each", "",
                "| | laya-multilingual | cbjev-multilingual |", "|---|---|---|",
                "| macro accuracy | %.4f | **%.4f** |" % (st.mean(a[k]["accuracy"] for k in langs), st.mean(b[k]["accuracy"] for k in langs)),
                "| macro ECE (lower is better) | %.4f | **%.4f** |" % (st.mean(a[k]["ece"] for k in langs), st.mean(b[k]["ece"] for k in langs)),
                "| languages where cbjev >= Laya | | **%d / %d** |" % (wins, len(langs)), "",
                "<details><summary>Per language</summary>", "", "| language | laya-multilingual | cbjev-multilingual | delta |",
                "|---|---|---|---|"]
        for k in langs:
            out.append("| %s | %.2f | %.2f | %+.2f |" % (k.split(".", 1)[1], a[k]["accuracy"], b[k]["accuracy"],
                                                     b[k]["accuracy"] - a[k]["accuracy"]))
        out += ["", "</details>", ""]
    sp = load("speed.json")
    if sp:
        keys = [k for k in sp["rows"][0] if k not in ("case", "questions")]
        out += ["## Latency", "", "Median of %d calls per cell, end to end through `predict` (validation, tokenization, "
                "forward, decoding), engines interleaved call by call on one %s (torch %s)."
                % (sp["meta"]["reps"], sp["meta"]["gpu"], sp["meta"]["torch"]), "",
                "| state | questions | " + " | ".join(keys) + " | cbjev speed-up vs fastest Laya |",
                "|---|---|" + "---|" * (len(keys) + 1)]
        for r in sp["rows"]:
            lay = min(r[k] for k in keys if k.startswith("laya"))
            out.append("| %s | %d | " % (r["case"], r["questions"]) + " | ".join("%.2f ms" % r[k] for k in keys) +
                       " | **%.1fx** |" % (lay / r["cbjev"]))
        out += ["", "TypeSafe Jev's hosted API has been measured at 236-276 ms p50 per call (AbdelStark/jev-benchmarks, "
                "nibzard/decision-model-benchmark), network included.", ""]
    rob = load("robustness.json")
    if rob:
        out += ["## Option-order robustness", "", "Share of questions whose answer changes when the options are "
                "reversed (lower is better). Jev: 0.13 (published, nibzard).", "",
                "| suite | " + " | ".join(rob["engines"]) + " |", "|---|" + "---|" * len(rob["engines"])]
        for s, row in rob["rows"].items():
            out.append("| %s | " % s + " | ".join("%.3f" % row[e] for e in rob["engines"]) + " |")
        out.append("")
    with open(os.path.join(os.path.dirname(HERE), "BENCHMARKS.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote BENCHMARKS.md")


if __name__ == "__main__":
    main()
